import {createRequire} from 'node:module';
import fs from 'node:fs/promises';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE_PATH||'playwright');
const browser=await chromium.launch({channel:process.env.PLAYWRIGHT_CHANNEL||'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1600,height:1000},deviceScaleFactor:1});
process.on('uncaughtException',async error=>{console.error(error);await page.screenshot({path:'artifacts/ui-failure.png'}).catch(()=>{});await browser.close();process.exit(1)});
const errors=[];page.on('pageerror',error=>errors.push(String(error)));
page.on('console',message=>{if(message.type()==='error')errors.push(message.text())});
await page.goto('http://127.0.0.1:8790');
await page.getByText('Tooling base',{exact:true}).first().waitFor({timeout:60000});
await page.waitForTimeout(2000);
await fs.mkdir('artifacts',{recursive:true});
await page.screenshot({path:'artifacts/workspace.png',fullPage:true});
const initial=await page.evaluate(async()=>fetch('/api/state').then(r=>r.json()));
const diameter=Object.values(initial.document.parameters).find(p=>p.name==='Concrete casting diameter');
if(!diameter)throw new Error('The mold reference fixture is not loaded.');
await page.getByRole('button',{name:'Parameters',exact:true}).click();
await page.getByRole('button',{name:'Concrete casting diameter Design inputs',exact:false}).click();
const dialog=page.getByRole('dialog',{name:'Edit dimension'});
await dialog.getByLabel('Value or expression',{exact:true}).fill('48 mm');
await dialog.getByRole('button',{name:'Preview impact',exact:true}).click();
await dialog.getByText('Candidate evaluated successfully',{exact:true}).waitFor();
const beforeCommit=await page.evaluate(async()=>fetch('/api/state').then(r=>r.json()));
if(beforeCommit.document.revision!==initial.document.revision)throw new Error('A preview incorrectly committed the design.');
await dialog.getByRole('button',{name:'Apply dimension',exact:true}).click();
await dialog.waitFor({state:'hidden'});
await page.getByRole('dialog',{name:'Dimensions, connected.'}).getByRole('button',{name:'Done',exact:true}).click();
await page.waitForTimeout(700);
const edited=await page.evaluate(async()=>fetch('/api/state').then(r=>r.json()));
if(edited.parameter_graph[diameter.id].value!==48)throw new Error('The manual parameter edit did not reach the engine.');
await page.getByRole('button',{name:'Undo',exact:true}).click();
await page.waitForFunction(async()=>{const s=await fetch('/api/state').then(r=>r.json());return Object.values(s.document.parameters).some(p=>p.name==='Concrete casting diameter'&&s.parameter_graph[p.id].value===44)});
await page.locator('.job-card').waitFor({state:'hidden'});
await page.locator('.component-select').filter({hasText:'Left removable form'}).click();
await page.getByRole('heading',{name:'Left removable form',exact:true}).waitFor();
await page.screenshot({path:'artifacts/component-inspection.png',fullPage:true});
await page.getByRole('button',{name:'Export STL',exact:false}).click();
await page.getByRole('dialog',{name:'Export precise parts'}).getByRole('button',{name:'Validate and export',exact:true}).click();
await page.getByRole('dialog',{name:'Your parts are ready.'}).waitFor({timeout:30000});
const exportText=await page.locator('.export-success').innerText();
await page.getByRole('dialog',{name:'Your parts are ready.'}).getByRole('button',{name:'Close dialog'}).click();
await page.locator('.timeline-feature').first().dblclick();
const compute=page.getByRole('dialog',{name:'Compute this build stage?'});
if(await compute.isVisible())await compute.getByRole('button',{name:'Compute explicitly'}).click();
await page.getByText('Inspecting build stage',{exact:true}).waitFor();
await page.getByRole('button',{name:'Return to present',exact:false}).click();
await page.getByText('At the current design',{exact:true}).waitFor();
console.log(JSON.stringify({title:await page.title(),canvasCount:await page.locator('canvas').count(),manualParameterPreviewAndEdit:true,undo:true,exportText,errors},null,2));
await browser.close();
if(errors.length)process.exitCode=1;
